/**
 * M7 · 图标资产导入（W2.5）
 *
 * lucide-static（ISC）的 `icon-nodes.json` 是结构化的 `[tag, attrs]` 数组——
 * 比解析 SVG 文本更可靠。本脚本把每个图标压成**一条 SVG path d**（24×24 本地坐标系），
 * 因为 UI AST 的 VECTOR 节点只承载单条 `vector.d`（多子路径已由 #16 修复支持）。
 *
 * 产物：`src/assets/icons/lucide.json`（面板动态 import，不进主包）
 * 用法：node scripts/icons-import.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NM = path.join(root, 'node_modules');
const OUT_DIR = path.join(root, 'src/assets/icons');

const nodes = JSON.parse(fs.readFileSync(path.join(NM, 'lucide-static/icon-nodes.json'), 'utf8'));
const tags = JSON.parse(fs.readFileSync(path.join(NM, 'lucide-static/tags.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(NM, 'lucide-static/package.json'), 'utf8'));

const n = (v) => {
  const num = Number(v);
  if (!Number.isFinite(num)) return String(v);
  return String(Math.round(num * 1000) / 1000);
};

/** 各 SVG 基本图形 → path d（与 Lucide 的 24×24 网格口径一致） */
function shapeToPath(tag, a) {
  switch (tag) {
    case 'path':
      return a.d;
    case 'line':
      return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
    case 'polyline':
    case 'polygon': {
      const pts = String(a.points).trim().split(/[\s,]+/).map(Number);
      if (pts.length < 4) return '';
      let d = `M${n(pts[0])} ${n(pts[1])}`;
      for (let i = 2; i + 1 < pts.length; i += 2) d += `L${n(pts[i])} ${n(pts[i + 1])}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle': {
      const cx = Number(a.cx);
      const cy = Number(a.cy);
      const r = Number(a.r);
      return `M${n(cx - r)} ${n(cy)}a${n(r)} ${n(r)} 0 1 0 ${n(r * 2)} 0a${n(r)} ${n(r)} 0 1 0 ${n(-r * 2)} 0`;
    }
    case 'ellipse': {
      const cx = Number(a.cx);
      const cy = Number(a.cy);
      const rx = Number(a.rx);
      const ry = Number(a.ry);
      return `M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(rx * 2)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-rx * 2)} 0`;
    }
    case 'rect': {
      const x = Number(a.x);
      const y = Number(a.y);
      const w = Number(a.width);
      const h = Number(a.height);
      const rx = a.rx != null ? Number(a.rx) : 0;
      const ry = a.ry != null ? Number(a.ry) : rx;
      if (!rx && !ry) return `M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}Z`;
      return (
        `M${n(x + rx)} ${n(y)}h${n(w - rx * 2)}a${n(rx)} ${n(ry)} 0 0 1 ${n(rx)} ${n(ry)}` +
        `v${n(h - ry * 2)}a${n(rx)} ${n(ry)} 0 0 1 ${n(-rx)} ${n(ry)}` +
        `h${n(-(w - rx * 2))}a${n(rx)} ${n(ry)} 0 0 1 ${n(-rx)} ${n(-ry)}` +
        `v${n(-(h - ry * 2))}a${n(rx)} ${n(ry)} 0 0 1 ${n(rx)} ${n(-ry)}Z`
      );
    }
    default:
      return '';
  }
}

const icons = {};
const unsupported = new Set();
let maxLen = 0;
let totalLen = 0;

for (const [name, shapeList] of Object.entries(nodes)) {
  if (!Array.isArray(shapeList)) continue;
  const parts = [];
  for (const shape of shapeList) {
    if (!Array.isArray(shape)) continue;
    const [tag, attrs] = shape;
    const d = shapeToPath(tag, attrs ?? {});
    if (d) parts.push(d);
    else unsupported.add(tag);
  }
  if (!parts.length) continue;
  const d = parts.join('');
  maxLen = Math.max(maxLen, d.length);
  totalLen += d.length;
  const tagText = (tags[name] ?? []).slice(0, 6).join(' ');
  icons[name] = { d, t: tagText };
}

const payload = {
  version: pkg.version,
  license: 'ISC',
  source: 'lucide-static',
  viewBox: 24,
  icons,
};

fs.mkdirSync(OUT_DIR, { recursive: true });
/**
 * 产物刻意写成 `.ts` 而非 `.json`：JSON 模块会让 TS 推断出 1545 键的字面量类型，
 * 拖慢 tsc；`.ts` 带显式类型标注，检查成本恒定。
 */
const file = path.join(OUT_DIR, 'lucide.ts');
const body = `/**
 * AUTO-GENERATED by scripts/icons-import.mjs —— 请勿手改。
 * 源：lucide-static v${payload.version}（ISC）。每个图标已压成单条 path d（24×24 坐标系）。
 * 体积：${Object.keys(icons).length} 个图标，动态 import 加载，不进主包。
 */
export interface IconEntry {
  /** SVG path d（24×24 本地坐标系，多子路径已合并） */
  d: string;
  /** 搜索用标签（空格分隔，源自 lucide tags.json） */
  t: string;
}

export const LUCIDE_VERSION = '${payload.version}';
export const LUCIDE_LICENSE = 'ISC';
export const LUCIDE_VIEWBOX = 24;

export const LUCIDE_ICONS: Record<string, IconEntry> = ${JSON.stringify(icons)};
`;
fs.writeFileSync(file, body, 'utf8');

const sizeKB = (fs.statSync(file).size / 1024).toFixed(1);
console.log(`✓ 图标 ${Object.keys(icons).length} 个 → ${path.relative(root, file)}`);
console.log(`  path 平均长度 ${(totalLen / Object.keys(icons).length).toFixed(0)} 字符，最长 ${maxLen}`);
console.log(`  产物体积 ${sizeKB} KB（面板动态 import，不进主包）`);
if (unsupported.size) console.log(`  跳过的图元：${[...unsupported].join(', ')}（Lucide 未使用/本脚本未覆盖）`);
