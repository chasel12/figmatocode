/** MVP 场景（priority === 1），共 10 个 */
export const MVP_SCENARIOS: UiScenario[] = UI_SCENARIOS.filter((s) => s.priority === 1);

export function scenarioById(id: string): UiScenario | undefined {
  return UI_SCENARIOS.find((s) => s.id === id);
}

/** 按组统计，供审计脚本打表 */
export function scenariosByGroup(): Record<string, UiScenario[]> {
  const out: Record<string, UiScenario[]> = {};
  for (const s of UI_SCENARIOS) (out[s.group] ??= []).push(s);
  return out;
}
