/**
 * UI 场景全集（反 bug 审计的输入）
 *
 * 用途：`scripts/ui-audit.ts` 逐条调真实模型生成，把产物存成 fixture，
 * 再跑机器扫描 + 人工看截图，**先看真实 bug，再写规则**。
 *
 * 为什么清单要写在这里而不是 markdown：
 *   脚本要能 import 它，人手写的 md 会漂移成两份（一份给脚本一份给人）。
 *   单一来源 = 场景改了，审计自动跟着变。
 *
 * 为什么 prompt 写得这么具体：
 *   需求含糊时模型会自由发挥，不同场景生成出同一个东西，测不出差异。
 *   每个 prompt 都钉死「元素 + 数量 + 状态」，让 45 个场景彼此不可替代。
 *
 * `risks` 不是猜测，是已发生过的 bug 归类（见 `docs/ai-ab-report.md` 附录与
 * `.workbuddy-ai/memory/MEMORY.md` 的「结构性教训」）。扫描器按它定向检查，
 * 但**扫描结果以实测为准**——`risks` 只是提示，不是结论。
 *
 * `priority: 1` 是 MVP 的 10 个：覆盖脱流 / 网格 / 对齐 / FIXED / 重复 / 基线
 * 六个高发区，且都是「第一眼就看得出好坏」的区域。
 */

export interface UiScenario {
  /** kebab-case 唯一 id，同时用作 fixture 目录名 */
  id: string;
  group: string;
  title: string;
  /** 交给模型的完整需求（含尺寸与元素清单） */
  prompt: string;
  /** 期望在产物里出现的结构特征，供机器校验「该有的有没有」 */
  expect: string[];
  /** 预期会暴露的 bug 类型（来自已知教训，不是结论） */
  risks: string[];
  /** 1 = MVP 必做；2 = 第二批；3 = 全量回归 */
  priority: 1 | 2 | 3;
}

